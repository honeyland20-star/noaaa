const assert=require('node:assert/strict');
const {study,liquidity,stories,contextMetric,buyFilter}=require('./app/src/main/assets/analysis');
const h=3600000,d=24*h,now=1800000000000,base=now-60*h;
const arr=Array.from({length:61},(_,i)=>i);
const candles={s:'ok',t:arr.map(i=>(base+i*h)/1000),o:arr.map(i=>200+i),c:arr.map(i=>201+i),l:arr.map(i=>199+i),h:arr.map(i=>202+i),v:arr.map(()=>1)};
const study1=study(candles,60,now);
assert.equal(study1.candles.length,60);assert.equal(study1.rsi,100);assert.equal(study1.trend,'صعودی');
assert.throws(()=>study({...candles,h:[1]},60,now));
assert.throws(()=>study(candles,60,now+3*h));assert.throws(()=>study({...candles,t:candles.t.map((t,i)=>i===40?t-100:t)},60,now));
const item={published:now,title:'ETF approval - Reuters',source:'Reuters'};
const news=stories([item,item,{...item,published:now-2*d}],now);assert.equal(news.items.length,1);
assert(buyFilter({minutes:60,candles:study1,macro:news},now));assert.equal(buyFilter({minutes:60,candles:{...study1,rsi:60},macro:news},now),'');
assert(buyFilter({minutes:60,candles:{...study1,rsi:60}},now));
assert.throws(()=>liquidity({lastUpdate:now-2*h,bids:[],asks:[]},now));
assert.equal(liquidity({lastUpdate:now,bids:[[100,3]],asks:[[100.5,2]]},now).stamp,now);
assert.throws(()=>contextMetric('mood',{data:[{timestamp:now/1000,value:null}]},now));
assert.throws(()=>contextMetric('social',{posts:[]},now));
const chain=Array.from({length:9},(_,i)=>({time:new Date(now-(8-i)*d).toISOString(),TxCnt:'100'}));assert.equal(contextMetric('chain',{data:chain},now).stamp,now);
const dated={data:{updated_at:now/1000,market_cap_change_percentage_24h_usd:2,market_cap_percentage:{btc:50},total_market_cap:{usd:1e12}}};
assert.equal(contextMetric('global',dated,now).stamp,now);
assert.throws(()=>contextMetric('global',dated,now+2*d));
console.log('Analysis fixtures passed');
const ctx={minutes:60,strict:true,candles:{...study1,rsi:60},macro:news};assert(buyFilter(ctx,now));
for(const key of ['global','fundamentals','funding','interest','chain','mood','social'])ctx[key]={lines:['ok']};
assert.equal(buyFilter(ctx,now),'');ctx.global.risk='افت بازار';assert(buyFilter(ctx,now).includes('افت بازار'));
